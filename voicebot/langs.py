def sorted_codes() -> list[str]:
    return sorted(LANGUAGES.keys(), key=lambda k: LANGUAGES[k][2])


def get_flag(code: str) -> str:
    entry = LANGUAGES.get(code)
    return entry[1] if entry else "🏳️"


def get_google_code(code: str) -> str:
    return LANGUAGES[code][0]


def get_deepl_target(code: str) -> str:
    return DEEPL_TARGET_MAP.get(code, code)


def normalize_deepl_code(code: str) -> str | None:
    """Приводит произвольный код, который может вернуть DeepL при детекте
    языка, к одному из поддерживаемых кодов LANGUAGES (или None)."""
    if not code:
        return None
    code = code.upper()
    if code in LANGUAGES:
        return code
    if code in DEEPL_ALIAS_MAP and DEEPL_ALIAS_MAP[code] in LANGUAGES:
        return DEEPL_ALIAS_MAP[code]
    prefix = code.split("-")[0]
    if prefix in LANGUAGES:
        return prefix
    if prefix in DEEPL_ALIAS_MAP and DEEPL_ALIAS_MAP[prefix] in LANGUAGES:
        return DEEPL_ALIAS_MAP[prefix]
    return None
